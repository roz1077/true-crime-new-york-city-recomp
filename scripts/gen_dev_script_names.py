# Writes src/dev/script_names.h for the dev debug menu: every name in the AI
# script .def files (state names among them), so the menu can show the stages
# of live scripts by name. Run from the repository root.
import glob

BACKSLASH = chr(92)


def quote(s):
    return '"' + s.replace(BACKSLASH, BACKSLASH * 2).replace('"', BACKSLASH + '"') + '"'


names = set()
for path in glob.glob('assets/data/ScriptDev/*.def'):
    for line in open(path, errors='ignore'):
        parts = line.strip().split(' ', 1)
        if len(parts) == 2 and parts[1] and parts[1] != '(null)':
            names.add(parts[1])
out = ['// Generated by scripts/gen_dev_script_names.py from assets/data/ScriptDev/*.def:',
       '// every name the AI scripts use (states among them), keyed at run time by CRC-32.',
       '#pragma once', '', 'namespace dev {', 'inline constexpr const char *kScriptNames[] = {']
out += ['    %s,' % quote(name) for name in sorted(names)]
out += ['};', '} // namespace dev', '']
open('src/dev/script_names.h', 'w', newline='\n').write('\n'.join(out))
print(len(names), 'names')
